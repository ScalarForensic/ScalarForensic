// Part of the sfn() Alpine component — merged by app.js. See app.js for load order.
(window.__sfnParts = window.__sfnParts || []).push({
    // ── Computed ──────────────────────────────────────────────────────────
    get progressPct() {
      // Total may be null on error events — treat as no-progress rather than dividing by zero.
      return !this.progress.total
        ? 0
        : Math.round(this.progress.current / this.progress.total * 100);
    },
    get selectedFile() {
      return this.results.find(r => r.file_id === this.selectedFileId) ?? null;
    },
    get isVideoUpload() {
      const f = this.selectedFile;
      return f ? this.isVideoFile(f.filename) : false;
    },
    get currentQueryFrame() {
      if (!this.queryFrames || !this.queryFrames.length) return null;
      return this.queryFrames[this.queryFrameIdx] ?? null;
    },
    // Timecode of the currently shown query frame, or null when not in video mode.
    // Used to dim hits that weren't generated by this frame (parent mode only).
    get activeQueryTimecode() {
      if (!this.isVideoUpload) return null;
      if (this.selectedFrameTimecode !== null) return this.selectedFrameTimecode;
      return this.currentQueryFrame ? this.currentQueryFrame.timecode_ms : null;
    },
    get matchedFiles() {
      return this.results.filter(r => r.hits.length > 0 && !(r.errors?.length > 0));
    },
    get errorFiles() {
      return this.results.filter(r => r.errors?.length > 0);
    },
    get unmatchedFiles() {
      return this.results.filter(r => r.hits.length === 0 && !(r.errors?.length > 0));
    },
    get selectedHit() {
      const hits = this.filteredHits;
      if (this.selectedHitKey) {
        const h = hits.find(h => this.hitKey(h) === this.selectedHitKey);
        if (h) return h;
      }
      return hits[0] ?? null;
    },
    // ── Face basket derivations (change-set 2026-08-13) ───────────────────
    // The basket is the single selection model; the wire formats fall out of
    // it here rather than living as parallel state that could drift.
    get selectedQueryFaceIndices() {
      return this.faceBasket
        .filter(r => r.side === 'query' && r.fileId === this.selectedFileId && r.selected)
        .map(r => r.faceIndex);
    },
    get selectedFacePointIds() {
      return this.faceBasket
        .filter(r => r.side === 'hit' && r.selected)
        .map(r => r.pointId);
    },
    // Pairs above the operator's floor, as membership sets for the two chip
    // strips.  Strictly above: at the 0.0 default a zero or negative cosine
    // does not read as "these match".
    get faceCrossHighlight() {
      const queryIndices = new Set();
      const pointIds = new Set();
      for (const p of this.faceComparePairs) {
        if (p.score > this.faceCrossThreshold) {
          queryIndices.add(p.query_face_index);
          pointIds.add(String(p.point_id));
        }
      }
      return { queryIndices, pointIds };
    },
    get mergedHits() {
      // Face hits arrive from a second endpoint; merge them into the image-mode
      // hit list by image_hash so one row is one medium across all four modes.
      const base = this.selectedFile ? this.selectedFile.hits : [];
      if (!this.faceHits.length) return base;
      const byHash = new Map();
      for (const fh of this.faceHits) byHash.set(fh.image_hash, fh);
      const merged = base.map(h => {
        const fh = byHash.get(h.image_hash);
        if (!fh) return h;
        byHash.delete(h.image_hash);
        return { ...h, scores: { ...h.scores, faces: fh.score }, face_match: fh.face };
      });
      // Media found only by face, appended score-desc.  `path` is set from
      // whichever locator the record has: hitKey() keys on it, so a null path
      // would collapse every face-only row onto one Alpine :key.
      const faceOnly = [...byHash.values()]
        .sort((a, b) => b.score - a.score)
        .map(fh => ({
          path: fh.image_path ?? fh.video_path ?? fh.image_hash,
          image_hash: fh.image_hash,
          scores: { faces: fh.score }, face_match: fh.face,
          is_video_frame: fh.is_video_frame, video_hash: fh.video_hash,
          video_path: fh.video_path, frame_timecode_ms: fh.frame_timecode_ms,
          exif: null, exif_geo_data: null, model_provenance: null,
          matched_frames: null, query_timecodes: null,
          best_query_timecode_ms: null, is_reference: false,
        }));
      return merged.concat(faceOnly);
    },
    get filteredHits() {
      if (!this.selectedFile) return [];
      let hits = this.mergedHits.filter(h => {
        // Keep if any active-mode score is present
        if ('exact' in h.scores) return true;
        if ('altered' in h.scores && this.hitsFilterAltered) return true;
        if ('semantic' in h.scores && this.hitsFilterSemantic) return true;
        if ('faces' in h.scores && this.hitsFilterFaces) return true;
        return false;
      });
      // When a specific query frame child is selected, show only that frame's hits
      if (this.selectedFrameTimecode !== null) {
        hits = hits.filter(h => h.query_timecodes?.includes(this.selectedFrameTimecode));
      }
      // Faces-only view: order by the face score — which is already the max
      // over the hit's observations (the backend collapses to the best one).
      // The unified view keeps the image-mode order.
      if (this.hitsFilterFaces && !this.hitsFilterAltered && !this.hitsFilterSemantic) {
        hits = [...hits].sort(
          (a, b) => (b.scores.faces ?? -Infinity) - (a.scores.faces ?? -Infinity));
      }
      return hits;
    },
    get selectedConcept() {
      return this.concepts.find(c => c.tag_id === this.selectedConceptId) ?? null;
    },
    tagHealth(tag) {
      // Thresholds derived from high-dimensional metric learning practice.
      // See docs/tag-triage.md §Collection health for the rationale.
      const p = tag.positive_ids.length;
      const n = tag.negative_ids.length;
      if (p < 50 || n < 20) return 'critical';
      if (p < 200 || n < 100) return 'marginal';
      if (p / n > 5 || n / p > 5) return 'marginal';
      return 'healthy';
    },
    get tagHealthByName() {
      const m = {};
      for (const c of this.concepts) m[c.name] = this.tagHealth(c);
      return m;
    },
    get exploreStrategyHint() {
      const c = this.selectedConcept;
      if (!c) return '';
      if (c.positive_ids.length > 0 && c.negative_ids.length > 0)
        return 'Boundary mode: surfaces points near the +/− decision boundary';
      return 'Random mode: returns a uniform sample — mark +/− to enable boundary mode';
    },
    get selectedTriageHit() {
      if (this.selectedTriageHitId) {
        const h = this.triageResults.find(h => String(h.point_id ?? h.file_id) === this.selectedTriageHitId);
        if (h) return h;
      }
      return this.triageResults[0] ?? null;
    },
    get effectiveMarks() {
      if (!this.selectedConceptId) return {};
      const c = this.selectedConcept;
      const marks = {};
      if (c) {
        for (const id of c.positive_ids) marks[String(id)] = 'positive';
        for (const id of c.negative_ids) marks[String(id)] = 'negative';
      }
      const ov = this.markedOverrides[this.selectedConceptId] ?? {};
      return { ...marks, ...ov };
    },
    get auditIntegrity() {
      if (!this.auditQueryLibVersions) return null;
      const rows = this._auditLibRows();
      const libMismatch = rows.filter(r => !r.match && r.indexed !== null).length;
      const modelMismatch = ['altered', 'semantic'].filter(m => this._modelMismatch(m)).length;
      return { libMismatch, modelMismatch, clean: libMismatch === 0 && modelMismatch === 0 };
    },
});
